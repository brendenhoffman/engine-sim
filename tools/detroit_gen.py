#!/usr/bin/env python3
"""Writes the Detroit Diesel two-stroke engine scripts (data/assets/engines/detroit/) from the
table in detroit_specs.json: their V layouts (crankpins, bank-timed injectors and exhaust cams)
are mechanical to lay out and easy to get wrong by hand.

  tools/detroit_gen.py              # write them all
  tools/detroit_gen.py 6v92ta.mr    # just these
"""
import json, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.environ.get('DETROIT_OUT', os.path.join(HERE, '..', 'data', 'assets', 'engines', 'detroit'))
SPECS = json.load(open(os.environ.get('DETROIT_SPECS', os.path.join(HERE, 'detroit_specs.json'))))

# Crankpin angles per bank (both banks share the pins). The right-bank cylinder on a pin fires
# 63.5 deg (the V angle) after the left.
PINS = {
    6: [0, 240, 120],
    8: [0, 270, 90, 180],
    12: [0, 240, 120, 30, 270, 150],
    16: [0, 270, 90, 180, 45, 315, 135, 225],
}
VEE = 63.5


def fmt(x):
    return ('%.4f' % x).rstrip('0').rstrip('.')


def gen(e):
    n = e['cylinders']
    per = n // 2
    pins = PINS[n]
    bore = 4.25 if e['series'] == 71 else 4.84
    stroke = 5.0
    swept_cc = 3.14159265 * (bore * 2.54) ** 2 / 4 * stroke * 2.54
    chamber = swept_cc / (e['compression'] - 1)
    disp_l = swept_cc * n / 1000
    turbo = e.get('turbo') is not None
    t = e.get('turbo') or {}
    # A cylinder reaches TDC when its pin lines up with its bank: at the pin angle less the bank
    # angle (left bank at +VEE/2, right at -VEE/2)
    fire = [[(p - VEE / 2) % 360 for p in pins], [(p + VEE / 2) % 360 for p in pins]]
    L = []
    w = L.append
    w('// ' + e['comment'].replace('\n', '\n// '))
    w('// Generated by tools/detroit_gen.py from tools/detroit_specs.json: bore %s in, stroke %s in, %d cylinders in a %.1f deg V.' % (bore, stroke, n, VEE))
    w('')
    w('import "engine_sim.mr"')
    w('import "themes/default.mr"')
    w('import "detroit_two_stroke.mr"')
    w('')
    w('units units()')
    w('constants constants()')
    w('impulse_response_library ir_lib()')
    w('')
    w('private node wires {')
    for i in range(n):
        w('    output wire%d: ignition_wire();' % (i + 1))
    w('}')
    w('')
    w('public node %s {' % e['node'])
    w('    alias output __out: engine;')
    w('')
    w('    engine engine(')
    w('        name: "%s",' % e['name'])
    w('        starter_torque: %d * units.lb_ft,' % e.get('starter_torque', 600 if n <= 8 else 1200))
    w('        starter_speed: 150 * units.rpm,')
    w('        redline: %d * units.rpm,' % (e['rated'] + 200))
    w('        cycle_angle: 360 * units.deg,       // Two-stroke: every cylinder fires every turn')
    w('        real_gas: 1,')
    for k, v in e.get('engine_inputs', {}).items():
        w('        %s: %s,' % (k, v))
    if e.get('pipe_resolution', 12):
        w('        pipe_resolution: %s,               // Waves in the exhaust pipes: the bark and rasp' % fmt(e.get('pipe_resolution', 12)))
    w('        friction_model: 1,')
    w('        fmep_constant: %s * units.kPa,      // Plain bearings, gear train, blower' % fmt(e.get('fmep', 60)))
    w('        idle_rpm: %d * units.rpm,' % e['idle'])
    w('        // The governor: mechanical, limiting speed')
    w('        diesel_idle_speed: %d * units.rpm,' % e['idle'])
    w('        diesel_rated_speed: %d * units.rpm,' % e['rated'])
    w('        diesel_fuel_per_injection: %s * units.g,' % fmt(e['fuel_mg'] / 1000))
    w('        diesel_peak_torque_speed: %d * units.rpm,' % e['peak_torque_rpm'])
    w('        diesel_rated_fuel: %s,' % fmt(e['rated_fuel']))
    w('        diesel_max_fuel: %s,                // Smoke limit' % fmt(e.get('max_fuel', 0.8)))
    w('        diesel_idle_max_fuel: %s,' % fmt(e.get('idle_max_fuel', 0.35)))
    w('        jake_brake_flow: k_carb(%s),' % fmt(e.get('jake', 60)))
    w('        combustion_noise: %s,' % fmt(e.get('combustion_noise', 0.0)))
    w('')
    w('        // Uniflow scavenging: air in through ports low in the liner, from the airbox the blower')
    w('        // fills; out through the exhaust valves in the head')
    w('        transfer_port_duration: %d * units.deg,' % e.get('port_duration', 120))
    w('        transfer_port_flow: k_carb(%s),' % fmt(e.get('port_flow', 600)))
    w('        crankcase_ratio: 0,                 // No crankcase pumping: the blower does it')
    w('        exhaust_port_duration: 0,           // Exhaust valves, not ports')
    w('        scavenging_quality: %s,             // Uniflow: the air pushes the exhaust out ahead of it' % fmt(e.get('scavenging', 2.0)))
    w('')
    w('        fuel: diesel_fuel(')
    # Cylinders matched closely (a clean, even bark under load); small idle deliveries scatter
    # (a ragged two-stroke idle)
    fuel_inputs = dict(injector_spread=0.01, idle_shot_variation=0.25)
    fuel_inputs.update({k: e[k] for k in ('injector_spread', 'shot_variation', 'idle_shot_variation', 'delay_variation') if k in e})
    extra = ''.join(',\n            %s: %s' % (k, fmt(v)) for k, v in fuel_inputs.items())
    w('            max_burning_efficiency: %s%s' % (fmt(e.get('burn_eff', 0.95)), extra))
    w('        ),')
    # Less of the pressure's derivative (upstream's 0.01 makes every engine bright) and some of the
    # plain pressure: the low-end weight. Noise 0.3 keeps some flow hash on each pulse.
    w('        hf_gain: %s,' % fmt(e.get('hf_gain', 0.002)))
    w('        noise: %s,' % fmt(e.get('noise', 0.3)))
    w('        jitter: %s,' % fmt(e.get('jitter', 0.25)))
    w('        simulation_frequency: %d' % e.get('sim_freq', 10000))
    w('    )')
    w('')
    w('    wires wires()')
    w('')
    w('    label stroke(%s * units.inch)' % fmt(stroke))
    w('    label bore(%s * units.inch)' % fmt(bore))
    w('    label rod_length(10.125 * units.inch)')
    w('    label rod_mass(%s * units.kg)' % fmt(4.0 if e['series'] == 71 else 4.6))
    w('    label compression_height(3.0 * units.inch)')
    w('    label crank_mass(%s * units.kg)' % fmt(12 * n))
    w('    label flywheel_mass(%s * units.kg)' % fmt(e.get('flywheel', 70)))
    w('    label flywheel_radius(9 * units.inch)')
    w('')
    w('    crankshaft c0(')
    w('        throw: stroke / 2,')
    w('        flywheel_mass: flywheel_mass,')
    w('        mass: crank_mass,')
    w('        friction_torque: 10.0 * units.lb_ft,')
    w('        moment_of_inertia:')
    w('            disk_moment_of_inertia(mass: crank_mass, radius: stroke / 2)')
    w('            + disk_moment_of_inertia(mass: flywheel_mass, radius: flywheel_radius)')
    w('            + disk_moment_of_inertia(mass: %s * units.kg, radius: 8.0 * units.cm),   // Blower, gear train, balancers' % fmt(5 * n))
    w('        position_x: 0.0,')
    w('        position_y: 0.0,')
    w('        tdc: constants.pi / 2')
    w('    )')
    w('')
    w('    // Each pin carries a left- and a right-bank rod side by side')
    for i, p in enumerate(pins):
        w('    rod_journal rj%d(angle: %d * units.deg)' % (i, p))
    w('    c0' + ''.join('\n        .add_rod_journal(rj%d)' % i for i in range(per)))
    w('')
    w('    piston_parameters piston_params(')
    w('        mass: %s * units.kg,' % fmt(3.5 if e['series'] == 71 else 4.2))
    w('        blowby: 0,')
    w('        compression_height: compression_height,')
    w('        wrist_pin_position: 0.0,')
    w('        displacement: 0.0')
    w('    )')
    w('    connecting_rod_parameters cr_params(')
    w('        mass: rod_mass,')
    w('        moment_of_inertia: rod_moment_of_inertia(mass: rod_mass, length: rod_length),')
    w('        center_of_mass: 0.0,')
    w('        length: rod_length')
    w('    )')
    w('    cylinder_bank_parameters bank_params(')
    w('        bore: bore,')
    w('        deck_height: stroke / 2 + rod_length + compression_height')
    w('    )')
    w('')
    w('    // The airbox around the liners: no throttle, the governor sets the fuel')
    w('    intake intake(')
    w('        plenum_volume: %s * units.L,' % fmt(2.5 * n))
    w('        plenum_cross_section_area: %s * units.cm2,' % fmt(25 * n))
    w('        intake_flow_rate: k_carb(%s),' % fmt(600 * n))
    w('        runner_flow_rate: k_carb(%s),' % fmt(e.get('runner_flow', 800)))
    w('        runner_length: %s * units.inch,' % fmt(e.get('runner_length', 2.0 if e['cylinders'] <= 8 else 10.0)))
    w('        idle_flow_rate: k_carb(0.0),')
    w('        idle_throttle_plate_position: 0.0')
    w('    )')
    w('')
    ex = e['exhaust']
    w('    exhaust_system_parameters es_params(')
    w('        outlet_flow_rate: k_carb(%s),' % fmt(ex['outlet_flow']))
    w('        primary_tube_length: %s * units.inch,' % fmt(ex.get('primary_length', 10)))
    w('        primary_flow_rate: k_carb(%s),' % fmt(ex.get('primary_flow', 800)))
    w('        velocity_decay: 1.0')
    w('    )')
    exhausts = 1 if turbo else 2
    for k in range(exhausts):
        w('    exhaust_system exhaust%d(' % k)
        w('        es_params,')
        w('        length: %s * units.inch,' % fmt(ex['length'] + 6 * k))
        w('        audio_volume: %s,' % fmt(ex.get('volume', 0.2)))
        w('        manifold_relative_sound: %s,' % fmt(ex.get('manifold_relative', 0.5)))
        w('        manifold_relative_sound_idle: %s,' % fmt(ex.get('manifold_relative_idle', 0.0)))
        w('        impulse_response: ir_lib.%s)' % ex.get('ir', 'straight_stack_0'))
    w('')
    b = e['blower']
    w('    // %s' % b['comment'])
    w('    forced_induction blower(')
    w('        intake: intake,')
    w('        exhaust_system: exhaust0,')
    w('        charge_volume: %s * units.L,' % fmt(b.get('charge_volume', 0.6 * n)))
    if turbo:
        w('        interstage_volume: %s * units.L,' % fmt(t.get('interstage_volume', 1.5 * n)))
        w('        intercooler: %s,' % fmt(e.get('aftercooler', 0.0)))
        w('        whine_floor: %s,' % fmt(t.get('whine_floor', 0.3)))
        w('        hiss_volume: %s,' % fmt(t.get('hiss', 0.3)))
    w('        whine_volume: %s' % fmt(b.get('whine_volume', 1.0)))
    w('    )')
    if turbo:
        w('    // No wastegate: the turbo is sized to the engine')
        for s in range(t.get('count', 1)):
            w('    blower.add_stage(')
            w('        turbocharger(')
            w('            compressor_radius: %s * units.mm,' % fmt(t['radius']))
            w('            compressor_flow: %s * units.kg / units.sec,' % fmt(t['flow']))
            w('            turbine_radius: %s * units.mm,' % fmt(t.get('turbine_radius', t['radius'])))
            w('            turbine_flow: k_carb(%s),' % fmt(t['turbine_flow']))
            w('            inertia: %s,' % fmt(t.get('inertia', 0.0006)))
            w('            max_speed: %d * units.rpm,' % t.get('max_speed', 100000))
            w('            duct_area: %s * units.cm2,' % fmt(t.get('duct_area', 50)))
            w('            whine_order: %s,' % fmt(t.get('whine_order', 13)))
            w('            feeds_blower: 1.0                   // Into the blower\'s inlet')
            w('        )')
            w('    )')
    w('    blower.add_stage(')
    w('        roots_supercharger(')
    w('            displacement: %s * units.cubic_inches,' % fmt(b['displacement']))
    w('            leakage: %s * units.cm2,' % fmt(b.get('leakage', 0.6 * n)))
    w('            efficiency: %s,' % fmt(b.get('efficiency', 0.6)))
    w('            drive_ratio: %s,' % fmt(b['drive_ratio']))
    w('            max_speed: 6000 * units.rpm,')
    w('            friction: %s,' % fmt(b.get('friction', 0.0005 * n / 6)))
    w('            lobes: 6.0,                        // Two three-lobe rotors')
    w('            gear_order: %s,' % fmt(b.get('gear_order', 0)))
    w('            gear_volume: %s' % fmt(b.get('gear_volume', 0.3)))
    w('        )')
    w('    )')
    w('')
    for k, name in enumerate(['left', 'right']):
        w('    cylinder_bank b%d(bank_params, angle: %s * units.deg)   // %s bank' % (k, fmt(VEE / 2 if k == 0 else -VEE / 2), name.capitalize()))
    w('')
    for k in range(2):
        w('    b%d' % k)
        for i in range(per):
            idx = k * per + i
            exh = 0 if turbo else k
            w('        .add_cylinder(')
            w('            piston: piston(piston_params, blowby: k_28inH2O(%s)),' % ('0.05' if (idx % 3) else '0.1'))
            w('            connecting_rod: connecting_rod(cr_params),')
            w('            rod_journal: rj%d,' % i)
            w('            intake: intake,')
            w('            exhaust_system: exhaust%d,' % exh)
            w('            ignition_wire: wires.wire%d,' % (idx + 1))
            spread = ex.get('primary_spread', 2)
            w('            primary_length: %s * units.inch,' % fmt(ex.get('primary_length_cyl', 4) + spread * abs(i - (per - 1) / 2)))
            att = ex.get('attenuation_spread', 0.0)
            w('            sound_attenuation: %s' % fmt(1 - att * (1 - [0.9, 0.95, 1.0, 0.93, 0.97, 0.92, 0.98, 0.94][idx % 8])))
            w('        )')
        w('')
    w('    engine.add_cylinder_bank(b0)')
    w('    engine.add_cylinder_bank(b1)')
    w('    engine.add_crankshaft(c0)')
    w('')
    w('    // The exhaust valves peak %d deg after each cylinder\'s TDC' % e.get('exhaust_center', 165))
    w('    detroit_exhaust_lobe exhaust_lobe(duration: %d * units.deg)' % e.get('exhaust_duration', 105))
    w('    camshaft_parameters cam_params(advance: 0.0, base_radius: 0.75 * units.inch)')
    for k in range(2):
        w('    camshaft exhaust_cam%d(cam_params, lobe_profile: exhaust_lobe)' % k)
        w('    exhaust_cam%d' % k + ''.join('\n        .add_lobe(%s * units.deg)' % fmt(e.get('exhaust_center', 165) + a) for a in fire[k]))
    w('')
    for k in range(2):
        w('    b%d.set_cylinder_head(' % k)
        w('        detroit_head(')
        w('            exhaust_camshaft: exhaust_cam%d,' % k)
        w('            chamber_volume: %s * units.cc,   // %s:1' % (fmt(chamber), fmt(e['compression'])))
        w('            flow_attenuation: %s%s' % (fmt(e.get('valve_flow', 1.6)), ',' if k == 1 else ''))
        if k == 1:
            w('            flip_display: true')
        w('        )')
        w('    )')
    w('')
    w('    // Start of injection, degrees before TDC (the unit injectors\' cam timing)')
    w('    function timing_curve(1000 * units.rpm)')
    w('    timing_curve')
    for rpm, deg in e.get('timing', [[0, 10], [1000, 12], [2000, 15], [3000, 16]]):
        w('        .add_sample(%d * units.rpm, %s * units.deg)' % (rpm, fmt(deg)))
    w('')
    w('    engine.add_ignition_module(')
    w('        ignition_module(timing_curve: timing_curve, rev_limit: %d * units.rpm, limiter_duration: 0.1)' % (e['rated'] + 600))
    order = sorted(((fire[k][i], k * per + i) for k in range(2) for i in range(per)))
    for ang, idx in order:
        w('            .connect_wire(wires.wire%d, %s * units.deg)' % (idx + 1, fmt(ang)))
    w('    )')
    w('}')
    w('')
    w('public node main {')
    w('    set_engine(%s())' % e['node'])
    w('    set_transmission(detroit_transmission())')
    w('    set_vehicle(detroit_truck())')
    w('}')
    w('')
    w('use_default_theme()')
    w('main()')
    w('')
    path = os.path.join(OUT, e['file'])
    open(path, 'w').write('\n'.join(L))
    return path, disp_l


if __name__ == '__main__':
    want = set(sys.argv[1:])
    for e in SPECS:
        if want and e['file'] not in want and e['node'] not in want:
            continue
        p, d = gen(e)
        print('%-40s %.2f L' % (os.path.basename(p), d))
